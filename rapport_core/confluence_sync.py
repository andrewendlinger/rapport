from .confluence_cli import state_folder
from .util import RapportError, atomic_write

INLINE = {"a", "abbr", "b", "br", "code", "del", "em", "i", "img", "input", "mark", "s", "small", "span", "strong",
          "sub", "sup", "time", "u", "#text"}
NOISE = {"data-local-id", "class", "style", "data-width", "data-colwidth-unit", "data-macro-id"}
BIG = 600   # chars: macro sources longer than this are summarised, not listed


def _short(text: str) -> str:
    return hashlib.sha1(text.encode()).hexdigest()[:8]


def _datauris(text: str) -> str:
    return re.sub(r"data:[\w/+.-]+;base64,[A-Za-z0-9+/=]+",
                  lambda m: f"data:…#{_short(m.group(0))}", text)


def _attrs(el: dom.El, skip=()) -> str:
    items = [(k, v) for k, v in sorted(el.attrs.items())
             if k not in NOISE and k not in skip and not (k == "data-layout" and v in ("default", "center"))]
    return " ".join(f"{k}={v}" if v != "" else k for k, v in items)


def _params(el: dom.El) -> dict:
    try:
        p = json.loads(el.get("data-parameters") or "{}")
    except json.JSONDecodeError:
        return {"unparsed": el.get("data-parameters")}
    if isinstance(p, dict):
        for k in ("macroMetadata", "extensionId", "extensionTitle", "forgeEnvironment"):
            p.pop(k, None)                      # Confluence's and Forge's bookkeeping
        if isinstance(p.get("macroParams"), dict):
            p["macroParams"].pop("_parentId", None)     # added when Confluence re-saves a page
            p["macroParams"].pop("legacyAnchorId", None)  # anchors: derived from the page title
        if p.get("layout") == "extension":
            p.pop("layout")
        for k in ("localId", "measuredHeight"):
            p.pop(k, None)
        if p.get("applyToAll") is False:        # native tabs, set by the editor
            p.pop("applyToAll")
        if isinstance(p.get("tabs"), list):      # tab IDs: generated by whoever made the tab
            p["tabs"] = [{k: v for k, v in t.items() if k != "id"} if isinstance(t, dict) else t for t in p["tabs"]]
    return p


def _canon(obj) -> str:
    return json.dumps(obj, sort_keys=True, ensure_ascii=False, separators=(",", ":"))


# ── inline ─────────────────────────────────────────────────────────────────────── #
# Formatting is read as a set, not a nesting: Confluence reorders nested marks and
# colour spans (<u><em><strong> comes back as <strong><em><u>), which changes nothing.
FORMAT_ORDER = ["**", "*", "~~", "<u>", "<sub>", "<sup>", "<mark>"]
FORMAT = {"strong": "**", "b": "**", "em": "*", "i": "*", "s": "~~", "del": "~~", "u": "<u>", "sub": "<sub>",
          "sup": "<sup>", "mark": "<mark>"}


def _is_format(n) -> bool:
    return isinstance(n, dom.El) and (n.tag in FORMAT or (n.tag == "span" and bool(n.get("style"))
                                                          and not n.get("data-type")))


def _formatted(el: dom.El) -> str:
    marks, props = set(), {}
    while True:
        if el.tag == "span":
            for part in (el.get("style") or "").split(";"):
                if ":" in part:
                    k, v = part.split(":", 1)
                    props[k.strip().lower()] = v.strip().lower()     # the innermost wins, as in Confluence
        else:
            marks.add(FORMAT[el.tag])
        kids = [c for c in el.children if not (isinstance(c, str) and not c.strip())]
        if len(kids) == 1 and _is_format(kids[0]):
            el = kids[0]
            continue
        break
    text = inline(el.children).strip()
    for m in reversed(FORMAT_ORDER):
        if m in marks:
            text = f"{m}{text}{m.replace('<', '</')}" if m.startswith("<") else f"{m}{text}{m}"
    if props:
        text = "{" + "; ".join(f"{k}: {v}" for k, v in sorted(props.items())) + f" | {text}}}"
    return text


def inline(nodes) -> str:
    out = []
    for n in nodes:
        if isinstance(n, str):
            out.append(re.sub(r"\s+", " ", n))
            continue
        t, dt = n.tag, n.get("data-type")
        if t == "br":
            out.append(" ⏎ ")
        elif t == "code":
            out.append(f"`{n.text()}`")
        elif _is_format(n):
            out.append(_formatted(n))
        elif t == "a":
            href = n.get("href") or n.get("data-url") or ""
            if n.get("data-card-appearance") == "inline":
                out.append(f"<card {href}>")
            else:
                out.append(f"[{inline(n.children).strip()}]({href})")
        elif t == "time":
            out.append(f"[date {n.get('datetime')}]")
        elif t == "input":
            continue
        elif t == "img":
            out.append(f"[img {_datauris(n.get('src') or '')} alt={n.get('alt') or ''}]")
        elif dt == "status":
            out.append(f"[status {n.get('data-color')} {n.get('data-status-style') or 'bold'}: {n.text().strip()}]")
        elif dt == "mention":
            out.append(f"[@{n.get('data-user-id') or n.text().strip()}]")
        elif dt == "emoji":
            out.append(n.get("data-emoji-short-name") or n.text())
        elif n.get("data-annotation-id") or "annotation" in (n.get("class") or ""):
            out.append(inline(n.children))      # inline-comment anchor: not content (listed separately)
        elif t == "span" and not n.attrs:
            out.append(inline(n.children))
        else:
            label = dt or t
            if dt in ("inline-extension", "extension"):
                label = f"ext {_extkey(n)} {_canon(_params(n))}"
            rest = _attrs(n, skip=("data-type", "data-parameters", "data-extension-key", "data-extension-type"))
            body = inline(n.children).strip()
            out.append(f"{{{label}{' ' + rest if rest else ''}{' | ' + body if body else ''}}}")
    return re.sub(r" {2,}", " ", "".join(out))


def _clean(text: str) -> str:
    return re.sub(r"\s*⏎\s*", " ⏎ ", text).strip()


# ── blocks ─────────────────────────────────────────────────────────────────────── #
def _is_block(n) -> bool:
    if isinstance(n, str):
        return False
    if n.tag == "a" and n.get("data-card-appearance") in ("block", "embed"):
        return True
    return n.tag not in INLINE


def _extkey(el: dom.El) -> str:
    key = el.get("data-extension-key") or ""
    return {MACRO_PACK: "macro-pack", DRAWIO: "drawio", INC_DRAWIO: "drawio-embed"}.get(key, key)


def _macro_pack(el: dom.El, pad: str) -> list[str]:
    gp = dict(_params(el).get("guestParams") or {})
    kind = gp.pop("input", "?")
    src = (gp.pop("source", None) or {}).get("text", "")
    gp.pop("version", None)
    head = f"{pad}[macro-pack {kind}{' ' + _canon(gp) if gp else ''}{_layout(el)}]"
    if kind == "drawio":
        labels = [re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", html_mod.unescape(v))).strip()
                  for v in re.findall(r'\bvalue="([^"]+)"', src)]
        return [head, f"{pad}    drawio xml #{_short(src)} ({len(src)} chars); labels: {' | '.join(labels)}"]
    fig = re.match(r'<figure data-rapport-src="([^"]+)"', src)
    if kind == "html" and fig:                                # an image the export inlined
        alt = re.search(r'\balt="([^"]*)"', src)
        return [f"{pad}[image {fig.group(1)} #{_short(src)}{' alt=' + alt.group(1) if alt else ''}]"]
    src = _datauris(src)
    if len(src) > BIG:
        return [head, f"{pad}    source #{_short(src)} ({len(src)} chars): {src[:120]}…"]
    return [head] + [f"{pad}    {line}" for line in src.splitlines()]


def _layout(el: dom.El) -> str:
    v = el.get("data-layout")
    return f" layout={v}" if v and v not in ("default", "center") else ""


def _blockstyle(el: dom.El) -> str:
    """Paragraph / heading styling that matters: alignment, indent, small text."""
    style = el.get("style") or ""
    out = []
    if m := re.search(r"text-align:\s*([\w-]+)", style):
        out.append(m.group(1))
    if m := re.search(r"margin-left:\s*([\d.]+)px", style):
        out.append(f"indent {int(float(m.group(1)) // 30)}")
    elif el.get("data-indent-level"):
        out.append(f"indent {el.get('data-indent-level')}")
    if re.search(r"font-size:", style):
        out.append("small")
    return "".join(f"[{x}] " for x in out)


def _breakout(el: dom.El, lead: str = "") -> str:
    """Full-width blocks. ("wide" at the default width is what the editor writes on
    its own when someone edits a block, so it's left out.)"""
    return f"{lead}full-width" if el.get("data-breakout") == "full-width" else ""


def _cell(el: dom.El) -> str:
    text = " ¶ ".join(line.strip() for line in blocks(el.children, 0))
    attrs = []
    for k in ("rowspan", "colspan"):
        if el.get(k) and el.get(k) != "1":
            attrs.append(f"{k}={el.get(k)}")
    if el.get("data-background"):
        attrs.append(f"bg={el.get('data-background').lower()}")
    if el.get("data-valign"):
        attrs.append(f"valign={el.get('data-valign')}")
    if el.get("data-colwidth"):
        attrs.append(f"w={el.get('data-colwidth')}")
    head = "th" if el.tag == "th" else ""
    meta = " ".join(([head] if head else []) + attrs)
    return f"{{{meta}}} {text}".strip() if meta else text


def _block(el: dom.El, pad: str) -> list[str]:
    t, dt = el.tag, el.get("data-type") or ""
    sub = pad + "  "
    if re.fullmatch(r"h[1-6]", t):
        return [f"{pad}{_blockstyle(el)}{'#' * int(t[1])} {_clean(inline(el.children))}"]
    if t == "p":
        pre = _blockstyle(el)
        text = _clean(inline(el.children))
        return [f"{pad}{pre}{text}"] if text else []
    if t in ("ul", "ol"):
        lines = []
        for li in el.elements:
            if li.tag in ("ul", "ol"):                       # a nested list straight in the list (task lists)
                lines += _block(li, sub)
                continue
            if dt == "task-list":
                box = li.find(lambda e: e.tag == "input")
                mark = "[x]" if box is not None and "checked" in box.attrs else "[ ]"
            elif dt == "decision-list":
                mark = f"[{(li.get('data-state') or '').lower()}]"
            else:
                mark = "1." if t == "ol" else "-"
            body = blocks(li.children, len(sub))
            first = body[0].strip() if body else ""
            lines.append(f"{pad}{mark} {first}".rstrip())
            lines += body[1:]
        return lines
    if t == "blockquote":
        return [f"{pad}> {line.strip()}" for line in blocks(el.children, 0)]
    if t == "pre":
        code = el.find(lambda e: e.tag == "code")
        lang = ((code.get("class") if code is not None else "") or "").replace("language-", "")
        flags = " ".join(f for f, k in (("wrap", "data-wrap"), ("no-line-numbers", "data-hide-line-numbers"))
                         if el.get(k) == "true")
        text = (code if code is not None else el).text()
        head = " ".join(x for x in ("code", lang, flags, _breakout(el)) if x)
        return [f"{pad}[{head}]"] + \
            [f"{pad}    {line}" for line in text.splitlines()]
    if t == "table":
        attrs = []
        if el.get("data-number-column") == "true":
            attrs.append("numbered")
        if el.get("data-display-mode"):
            attrs.append(el.get("data-display-mode"))
        if el.get("data-layout") and el.get("data-layout") not in ("default", "center"):
            attrs.append(el.get("data-layout"))
        lines = [f"{pad}[table{' ' + ' '.join(attrs) if attrs else ''}]"]
        for tr in el.find_all(lambda e: e.tag == "tr"):
            cells = [c for c in tr.elements if c.tag in ("td", "th")]
            lines.append(f"{pad}| " + " | ".join(_cell(c) for c in cells) + " |")
        return lines
    if t == "hr":
        return [f"{pad}---"]
    if t == "details":
        summary = el.find(lambda e: e.tag == "summary")
        title = _clean(inline(summary.children)) if summary is not None else ""
        rest = [c for c in el.children if c is not summary]
        return [f"{pad}[expand{_breakout(el, ' ')}: {title}]"] + blocks(rest, len(sub))
    if t == "a":                                              # block / embed card written as a link
        return [f"{pad}[card {el.get('data-card-appearance')} {el.get('href')}]"]
    if dt in ("block-card", "embed-card"):
        frame = el.find(lambda e: e.tag in ("iframe", "a"))
        url = el.get("data-url") or (frame.get("src") or frame.get("href") if frame is not None else "")
        return [f"{pad}[card {dt.split('-')[0]} {url}]"]
    if dt.startswith("panel-"):
        extra = " ".join(f"{k}={v}" for k, v in ((k, el.get(f"data-{k}")) for k in ("icon", "color")) if v)
        return [f"{pad}[{dt}{' ' + extra.lower() if extra else ''}]"] + blocks(el.children, len(sub))
    if t == "section" and dt.startswith("layout"):
        rule = el.get("data-column-rule-style")
        lines = [f"{pad}[{dt}{' rule=' + rule if rule else ''}{_breakout(el, ' ')}]"]
        for col in el.elements:
            lines.append(f"{sub}[column]")
            lines += blocks(col.children, len(sub) + 2)
        return lines
    if dt in ("extension", "bodied-extension", "multi-bodied-extension"):
        key = _extkey(el)
        if key == "macro-pack":
            return _macro_pack(el, pad)
        lines = [f"{pad}[{dt} {key} {_canon(_params(el))}{_layout(el)}]"]
        if dt == "multi-bodied-extension":
            for frame in el.elements:
                lines.append(f"{sub}[frame]")
                lines += blocks(frame.children, len(sub) + 2)
        elif dt == "bodied-extension":
            lines += blocks(el.children, len(sub))
        return lines
    if t == "figure" and el.get("data-rapport-src"):
        return [f"{pad}[image {el.get('data-rapport-src')}]"]
    rest = _attrs(el, skip=("data-type",))
    label = dt or t
    return [f"{pad}[{label}{' ' + rest if rest else ''}]"] + blocks(el.children, len(sub))


def blocks(nodes, depth: int = 0) -> list[str]:
    pad, lines, run = " " * depth, [], []

    def flush():
        text = _clean(inline(run))
        if text:
            lines.append(pad + text)
        run.clear()

    for n in nodes:
        if _is_block(n):
            flush()
            lines += _block(n, pad)
        else:
            run.append(n)
    flush()
    return lines


def outline(body: str) -> list[str]:
    """The page as comparable lines (see the module docstring)."""
    return blocks(dom.parse(body).children)


def comments(body: str) -> list[tuple[str, str]]:
    """Inline-comment anchors on the page: (annotation id, the text they mark)."""
    root = dom.parse(body)
    hits = root.find_all(lambda e: bool(e.get("data-annotation-id")))
    return [(e.get("data-annotation-id"), re.sub(r"\s+", " ", e.text()).strip()) for e in hits]


# ── diffs ──────────────────────────────────────────────────────────────────────── #
def _words(a: str, b: str) -> str | None:
    tok = re.compile(r"\[[ x]\]|\s+|\w+|[^\w\s]")
    ta, tb = tok.findall(a), tok.findall(b)
    sm = difflib.SequenceMatcher(None, ta, tb, autojunk=False)
    def weight(toks):
        return sum(len(t) for t in toks if re.search(r"\w", t))
    kept = sum(weight(ta[m.a:m.a + m.size]) for m in sm.get_matching_blocks())
    if kept < 0.5 * min(weight(ta), weight(tb)):               # mostly rewritten: show both lines
        return None
    out = []
    for op, i1, i2, j1, j2 in sm.get_opcodes():
        if op == "equal":
            out.append("".join(ta[i1:i2]))
            continue
        if i2 > i1:
            out.append("[-" + "".join(ta[i1:i2]) + "-]")
        if j2 > j1:
            out.append("{+" + "".join(tb[j1:j2]) + "+}")
    return "".join(out)


def render_diff(a: list[str], b: list[str], context: int = 1) -> str:
    """A compact diff: hunks headed by their section, one-for-one line edits shown
    word by word ([-old-]{+new+}), other lines as -/+."""
    heads = {}
    current = "(top)"
    for i, line in enumerate(a):
        if re.match(r"#{1,6} ", line):
            current = line
        heads[i] = current
    out = []
    sm = difflib.SequenceMatcher(None, a, b, autojunk=False)
    for group in sm.get_grouped_opcodes(context):
        out.append(f"@@ {heads.get(group[0][1], current)} @@")
        for op, i1, i2, j1, j2 in group:
            if op == "equal":
                out += [f"  {line}" for line in a[i1:i2]]
            elif op == "replace" and i2 - i1 == j2 - j1:
                for x, y in zip(a[i1:i2], b[j1:j2]):
                    w = _words(x, y)
                    out += [f"~ {w}"] if w is not None else [f"- {x}", f"+ {y}"]
            else:
                out += [f"- {line}" for line in a[i1:i2]] + [f"+ {line}" for line in b[j1:j2]]
    return "\n".join(out)


# ── state ──────────────────────────────────────────────────────────────────────── #
def _paths(report_dir: Path) -> tuple[Path, Path]:
    d = state_folder(report_dir)
    return d / "base.html", d / "page.json"


def _publish_path(report_dir: Path) -> Path:
    return state_folder(report_dir) / "publish.json"


def _same_page(report_dir: Path, page: dict) -> None:
    """Refuse a page file that isn't the page this report was published to."""
    _, meta = _paths(report_dir)
    if meta.is_file():
        known = str(json.loads(meta.read_text(encoding="utf-8")).get("page_id") or "")
        if known and page.get("id") and str(page["id"]) != known:
            raise RapportError(f"this report was published to page {known}, not {page['id']}")


def record(report_dir: Path, page: dict, quiet: bool = False, force: bool = False, sets=None) -> int:
    """Store the published page as the base. After `prepare`, confirm the publish:
    the page went up exactly one version (no one else saved in between) and
    Confluence stored what was sent. After a first publish, compare it with the
    export. Replacing an existing base any other way would bless edits report.md
    lacks (and `prepare` would then overwrite them), so that needs `force`."""
    base, meta = _paths(report_dir)
    warnings = []
    pub_file = _publish_path(report_dir)
    got = page.get("version")
    if pub_file.is_file():
        pub = json.loads(pub_file.read_text(encoding="utf-8"))
        if str(page.get("id")) != str(pub.get("page_id")) and not force:
            raise RapportError(f"prepared for page {pub.get('page_id')}, not {page.get('id')}")
        expected = pub.get("expected_version") or 0
        if got <= expected:
            raise RapportError(f"the page is still at version {got}: publish `publish.html` first "
                               f"(prepared over version {expected})")
        if got > expected + 1:
            warnings.append(f"the page went from version {expected} to {got}: someone saved between `prepare` and "
                            "the publish, and the publish replaced their version. Ask the user to compare the "
                            "versions in the page history and restore their change")
        sent = Path(pub.get("body_file") or "")
        if sent.is_file() and (a := outline(sent.read_text(encoding="utf-8"))) != (b := outline(page["body"])):
            warnings.append("Confluence stored the page differently from what was sent:\n" + render_diff(a, b))
        pub_file.unlink()
    elif base.is_file():
        _same_page(report_dir, page) if not force else None
        if not force and (problems := _problems(report_dir, page, _export(report_dir, sets))):
            raise RapportError("not recording: the page has changes report.md lacks, and recording it as the base "
                               "would let the next publish overwrite them. Bring them back first "
                               "(`rapport confluence diff`), or pass --force:\n  " + "\n  ".join(problems))
    else:
        sent = state_folder(report_dir) / "export.html"           # a first publish: compare with the export
        if sent.is_file() and (a := outline(sent.read_text(encoding="utf-8"))) != (b := outline(page["body"])):
            warnings.append("Confluence stored the page differently from the export:\n" + render_diff(a, b))
    atomic_write(base, page["body"])
    info = {"page_id": page.get("id") or "", "version": got, "title": page.get("title") or "",
            "recorded": datetime.now(timezone.utc).isoformat(timespec="seconds")}
    atomic_write(meta, json.dumps(info, indent=2, ensure_ascii=False) + "\n")
    if not quiet:
        print(f"recorded page {info['page_id']} version {got} as the base")
    for w in warnings:
        print(f"warning: {w}")
    return 1 if warnings else 0


def _base(report_dir: Path) -> tuple[str, dict]:
    base, meta = _paths(report_dir)
    if not base.is_file():
        raise RapportError("no recorded publish for this report. If it was never published: publish it first "
                           "(export, create the page, record). If the page exists already and wasn't made from "
                           "this report, follow \"Taking over an existing page\" in references/confluence.md")
    info = json.loads(meta.read_text(encoding="utf-8")) if meta.is_file() else {}
    return base.read_text(encoding="utf-8"), info


def _export(report_dir: Path, sets=None):
    from .confluence import export
    res = export(report_dir, sets)
    if not res.ok:
        raise RapportError("report.md doesn't export: " + "; ".join(e.format("report.md") for e in res.errors))
    return res


def _local(report_dir: Path, sets=None) -> str:
    return _export(report_dir, sets).body


def diff(report_dir: Path, page: dict, local: bool = False, sets=None) -> int:
    base_html, info = _base(report_dir)
    a = outline(base_html)
    if local:
        b, what = outline(_local(report_dir, sets)), "report.md"
    else:
        _same_page(report_dir, page)
        b, what = outline(page["body"]), "confluence"
        print(f"page {info.get('page_id')}: last publish version {info.get('version')}, "
              f"live version {page.get('version')}")
        if info.get("title") and page.get("title") and page["title"] != info["title"]:
            print(f"confluence: title changed: “{info['title']}” → “{page['title']}”")
    if a == b:
        print(f"{what}: no changes since the last publish")
    else:
        print(f"{what}: changes since the last publish ([-removed-] {{+added+}}; - / + whole blocks)")
        print(render_diff(a, b))
    if not local:
        for cid, text in comments(page["body"]):
            print(f"inline comment {cid} on: “{text}”")
    return 0


def _order(seq: list[str], keep: Counter) -> list[str]:
    left, out = Counter(keep), []
    for line in seq:
        if left[line] > 0:
            out.append(line)
            left[line] -= 1
    return out


def _problems(report_dir: Path, page: dict, res) -> list[str]:
    """What Confluence changed since the base that the export doesn't have: blocks
    added, changed or removed, blocks moved, a renamed title."""
    base_html, info = _base(report_dir)
    b_lines, l_lines, r_lines = outline(base_html), outline(page["body"]), outline(res.body)
    base, live, local = Counter(b_lines), Counter(l_lines), Counter(r_lines)
    added, removed = live - base, base - live
    out = [f"missing in report.md: {line.strip()}" for line in added if local[line] < live[line]]
    out += [f"removed in Confluence, still in report.md: {line.strip()}" for line in removed if local[line] > live[line]]
    # moves: blocks all three share must keep the order Confluence gave them
    shared = base & live & local
    in_base, in_live, in_local = _order(b_lines, shared), _order(l_lines, shared), _order(r_lines, shared)
    if in_live != in_base and in_local != in_live:
        k = next(n for n, (x, y) in enumerate(zip(in_live, in_local)) if x != y)
        out.append(f"moved in Confluence: “{in_live[k].strip()}” now comes before “{in_local[k].strip()}”; "
                   "match the order in report.md")
    if info.get("title") and page.get("title") and page["title"] != info["title"] and res.title != page["title"]:
        out.append(f"title changed in Confluence to “{page['title']}”; report.md's title is “{res.title}”")
    return out


def check(report_dir: Path, page: dict, sets=None) -> int:
    """Every change Confluence made since the last publish must be in the report's
    export (local edits elsewhere are fine)."""
    _same_page(report_dir, page)
    problems = _problems(report_dir, page, _export(report_dir, sets))
    if problems:
        print("\n".join(problems))
        return 1
    base_html, _ = _base(report_dir)
    same = outline(base_html) == outline(page["body"])
    print("ok: Confluence has no changes since the last publish" if same else
          "ok: all Confluence changes are in report.md")
    return 0


# ── safe publishing ────────────────────────────────────────────────────────────── #
_TAG = re.compile(r"(<[^>]*>)")
_BLOCK_TAG = re.compile(r"</?(p|li|td|th|tr|h[1-6]|div|section|details|summary|pre|blockquote|table|ul|ol|figure)\b", re.I)
_CONTEXT = 40          # characters of neighbouring text compared on each side


def _norm(text: str) -> str:
    return text.replace("\xa0", " ")


def carry_comments(body: str, live: str) -> tuple[str, list[tuple[str, str]]]:
    """Put the live page's inline-comment anchors into a new body, around the same
    text. Where that text occurs more than once, the occurrence whose neighbouring
    text in the same block matches best wins. Returns the body and the comments
    that can't be placed: their text is gone, or two places fit equally well."""
    root = dom.parse(live)
    anchors = root.find_all(lambda e: bool(e.get("data-annotation-id")))
    lost = []
    for a in anchors:
        cid, target = a.get("data-annotation-id"), _norm(a.text())
        if not target.strip() or f'data-annotation-id="{cid}"' in body:
            continue
        before, after = _block_context(a)
        attrs = {key: a.get(key) for key in ("class", "data-annotation-id", "data-annotation-type") if a.get(key)}
        body, ok = _wrap_best(body, target, before, after, attrs)
        if not ok:
            lost.append((cid, re.sub(r"\s+", " ", target).strip()))
    return body, lost


def _block_context(a: dom.El) -> tuple[str, str]:
    """The text before and after an anchor within its block (paragraph, item, cell)."""
    block = a.parent
    while block is not None and block.tag not in ("p", "li", "td", "th", "h1", "h2", "h3", "h4", "h5", "h6",
                                                  "pre", "summary", "#root"):
        block = block.parent
    parts, seen = [[], []], [0]

    def walk(n):
        for c in n.children:
            if c is a:
                seen[0] = 1
            elif isinstance(c, str):
                parts[seen[0]].append(c)
            else:
                walk(c)
    walk(block if block is not None else a)
    return _norm("".join(parts[0])), _norm("".join(parts[1]))


def _common(a: str, b: str, from_end: bool) -> int:
    n = 0
    for x, y in zip(reversed(a) if from_end else a, reversed(b) if from_end else b):
        if x != y:
            break
        n += 1
    return n


def _wrap_best(body: str, target: str, before: str, after: str, attrs: dict) -> tuple[str, bool]:
    parts = _TAG.split(body)
    # the body as plain text, blocks separated by "\n", to read each hit's neighbours
    flat, offsets = [], {}
    for i, part in enumerate(parts):
        if part.startswith("<"):
            if _BLOCK_TAG.match(part):
                flat.append("\n")
            continue
        offsets[i] = sum(len(x) for x in flat)
        flat.append(_norm(html_mod.unescape(part)))
    text_all = "".join(flat)
    edges = (bool(re.match(r"\w", before[-1:])), bool(re.match(r"\w", after[:1])))
    hits = []
    for i, start in offsets.items():
        seg = _norm(html_mod.unescape(parts[i]))
        for j in _hits(seg, target, edges):
            pos = start + j
            left = text_all[:pos].rsplit("\n", 1)[-1]
            right = text_all[pos + len(target):].split("\n", 1)[0]
            score = _common(before[-_CONTEXT:], left[-_CONTEXT:], True) + _common(after[:_CONTEXT], right[:_CONTEXT], False)
            hits.append((score, i, j))
    if not hits:
        return body, False
    best = max(h[0] for h in hits)
    top = [h for h in hits if h[0] == best]
    if len(top) > 1:
        return body, False                      # two places fit equally well: don't guess
    _, i, j = top[0]
    raw = html_mod.unescape(parts[i])
    attr = "".join(f' {key}="{html_mod.escape(v, quote=True)}"' for key, v in attrs.items())
    parts[i] = (html_mod.escape(raw[:j], quote=False) + f"<span{attr}>" + html_mod.escape(raw[j:j + len(target)], quote=False)
                + "</span>" + html_mod.escape(raw[j + len(target):], quote=False))
    return "".join(parts), True


def _hits(text: str, target: str, edges: tuple[bool, bool]) -> list[int]:
    """Where target occurs in text with the same word edges as the anchored spot
    (so a comment on "one" doesn't land inside "none")."""
    out, start = [], 0
    while (j := text.find(target, start)) >= 0:
        pre = bool(re.match(r"\w", text[j - 1:j])) if j else False
        post = bool(re.match(r"\w", text[j + len(target):j + len(target) + 1]))
        if (pre, post) == edges:
            out.append(j)
        start = j + 1
    return out


def prepare(report_dir: Path, page: dict, sets=None, detach: list[str] | None = None) -> int:
    """The body to publish over a live page, or a refusal: Confluence has changes
    report.md lacks, or an inline comment can't be kept. Writes publish.html and
    publish.json (page ID, the version checked, title)."""
    _, info = _base(report_dir)
    if not page.get("id") or not page.get("version"):
        raise RapportError("the live page needs its id and version: pass the getConfluencePage JSON")
    _same_page(report_dir, page)
    res = _export(report_dir, sets)
    problems = _problems(report_dir, page, res)
    if problems:
        print("not publishing: Confluence has changes that aren't in report.md (`rapport confluence diff`):")
        print("\n".join(f"  {p}" for p in problems))
        return 1
    body, lost = carry_comments(res.body, page["body"])
    lost = [(cid, text) for cid, text in lost if cid not in (detach or [])]
    if lost:
        print("not publishing: these inline comments would come loose (their text changed in report.md):")
        for cid, text in lost:
            print(f"  {cid} on “{text}”")
        print("Resolve them in Confluence, restore their text, or pass --detach <id> once the user agrees.")
        return 1
    d = state_folder(report_dir)
    atomic_write(d / "publish.html", body)
    pub = {"page_id": str(page.get("id") or info.get("page_id") or ""), "expected_version": page.get("version"),
           "title": res.title, "body_file": str(d / "publish.html"),
           "length": len(body.encode("utf-16-le")) // 2}      # as JavaScript counts it: check a full read
    atomic_write(_publish_path(report_dir), json.dumps(pub, indent=2, ensure_ascii=False) + "\n")
    kept = len(comments(page["body"]))
    print(f"ready: {d / 'publish.html'} ({len(body.encode()) // 1024 + 1} KB), title “{res.title}”")
    print(f"publish over page {pub['page_id']} only while it is still at version {pub['expected_version']}; "
          f"then fetch it back and `rapport confluence record` it")
    if kept:
        print(f"{kept} inline comment anchor(s) kept")
    for w in res.warnings:
        print(f"warning: {w}")
    for h in res.handovers:
        print(f"for the user: {h}")
    return 0
