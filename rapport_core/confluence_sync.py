"""Keep a report and its Confluence page in sync. The report is the source; the
page is a published copy that people also edit. rapport never contacts
Confluence: the agent fetches and publishes pages with its own tools and hands
the fetched page (HTML, or getConfluencePage JSON) to these commands.

record   after publishing, store the page as published (the base), and confirm
         the publish went as intended
diff     what changed in Confluence since then (or in report.md: --local), as a
         short readable outline diff; the agent applies those edits itself
check    are all of Confluence's changes in report.md now? (exit 1 if not)
prepare  the body to publish over the live page, or a refusal (Confluence changes
         report.md lacks, an inline comment that can't be kept)

All comparisons run on an outline of the page: one line per block, inline marks
as compact Markdown-ish text, with Confluence's noise removed (local IDs, macro
IDs, attribute order, <p> inside list items and cells, default layouts, …) and
big payloads (diagram XML, inlined images) collapsed to a short hash.
"""

from __future__ import annotations

import difflib
import hashlib
import html as html_mod
import json
import re
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

from . import dom
